/* Provider compare view (/compare/?compare=a,b — 2 to 4 slugs, #175).
   The table comes from shared-compare.js (window.FLLM_COMPARE), generated by
   scripts/build.mjs from scripts/lib/compare.mjs — the same function that
   renders the static /compare/<a>-vs-<b>/ pages, which escapes every provider
   field before it reaches innerHTML. This file only wires the picker and URL. */
(function () {
  var C = window.FLLM_COMPARE;
  var form = document.getElementById('compare-form');
  var out = document.getElementById('compare-out');
  if (!C || !form || !out) return;
  var selects = Array.prototype.slice.call(form.querySelectorAll('select[name="p"]'));
  var DATA = [];

  function message(text) {
    out.textContent = '';
    var p = document.createElement('p');
    p.className = 'muted';
    p.textContent = text;
    out.appendChild(p);
  }

  // The selection as a query string, so the same parser handles the picker,
  // a shared ?compare= link and the no-JS form submission (?p=a&p=b).
  function selected() {
    var q = new URLSearchParams();
    selects.forEach(function (s) { if (s.value) q.append('p', s.value); });
    return C.parseCompareSlugs(q.toString(), DATA.map(function (p) { return p.slug; }));
  }

  function show(slugs) {
    var list = slugs.map(function (s) { return DATA.find(function (p) { return p.slug === s; }); }).filter(Boolean);
    history.replaceState(null, '', slugs.length ? '?compare=' + slugs.join(',') : location.pathname);
    if (list.length < C.COMPARE_MIN) { message('Pick at least ' + C.COMPARE_MIN + ' providers to compare.'); return; }
    out.innerHTML = C.compareTableHtml(list, { prefix: '../' });
  }

  function fill(slugs) {
    selects.forEach(function (s, i) { s.value = slugs[i] || ''; });
  }

  form.addEventListener('submit', function (e) { e.preventDefault(); show(selected()); });
  selects.forEach(function (s) { s.addEventListener('change', function () { show(selected()); }); });

  fetch('../providers.json')
    .then(function (r) { if (!r.ok) throw new Error(String(r.status)); return r.json(); })
    .then(function (d) {
      DATA = (d && d.providers) || [];
      var slugs = C.parseCompareSlugs(location.search, DATA.map(function (p) { return p.slug; }));
      fill(slugs);
      show(slugs);
    })
    .catch(function () { message('Could not load the dataset. The comparisons below still work.'); });
})();
