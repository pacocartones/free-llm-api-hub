#!/usr/bin/env node
// Generate the provider field reference from JSON Schema, without inferred descriptions.
// node scripts/schema-docs.mjs [schema.json] [schema.md]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const DEFAULT_SCHEMA = fileURLToPath(new URL('../data/schema.json', import.meta.url));
const DEFAULT_OUTPUT = fileURLToPath(new URL('../docs/schema.md', import.meta.url));
const cell = (value) => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;').replaceAll('|', '&#124;').replace(/\r\n?|\n/g, '<br>');
const code = (value) => `<code>${cell(value)}</code>`;
const literal = (value) => code(JSON.stringify(value));

// Resolve only local references; a missing or cyclic definition must fail the
// build rather than silently publish an incomplete type.
function dereference(node, schema, seen = new Set()) {
  if (!node.$ref) return node;
  const ref = node.$ref;
  if (!ref.startsWith('#/') || seen.has(ref)) throw new Error(`Unsupported or cyclic schema reference: ${ref}`);
  const target = ref.slice(2).split('/').reduce((value, part) => value?.[part.replaceAll('~1', '/').replaceAll('~0', '~')], schema);
  if (!target || typeof target !== 'object') throw new Error(`Missing schema reference: ${ref}`);
  const { $ref, ...siblings } = node;
  return { ...dereference(target, schema, new Set([...seen, ref])), ...siblings };
}

function types(node, schema) {
  node = dereference(node, schema);
  if (node.type) return Array.isArray(node.type) ? node.type : [node.type];
  if (node.anyOf) return [...new Set(node.anyOf.flatMap((branch) => types(branch, schema)))];
  const values = node.enum ?? (Object.hasOwn(node, 'const') ? [node.const] : []);
  return [...new Set(values.map((value) => value === null ? 'null' : typeof value))];
}

function constraints(node, schema) {
  node = dereference(node, schema);
  const parts = [];
  if (node.enum) parts.push(`Allowed: ${node.enum.map(literal).join(', ')}`);
  if (Object.hasOwn(node, 'const')) parts.push(`Value: ${literal(node.const)}`);
  if (node.anyOf) parts.push(`One of: ${node.anyOf.map((branch) => {
    const detail = constraints(branch, schema);
    return `(${detail || `Type: ${types(branch, schema).join(' or ')}`})`;
  }).join(' OR ')}`);
  for (const [key, label] of [
    ['minimum', 'minimum'], ['maximum', 'maximum'],
    ['exclusiveMinimum', 'exclusive minimum'], ['exclusiveMaximum', 'exclusive maximum'],
    ['minLength', 'min length'], ['maxLength', 'max length'],
    ['minItems', 'min items'], ['maxItems', 'max items'],
    ['minProperties', 'min properties'], ['maxProperties', 'max properties'],
  ]) if (node[key] !== undefined) parts.push(`${label}: ${node[key]}`);
  if (node.format) parts.push(`Format: ${code(node.format)}`);
  if (node.pattern) parts.push(`Pattern: ${code(node.pattern)}`);
  if (node.uniqueItems) parts.push('Unique items');
  if (node.additionalProperties === false) parts.push('No additional properties');
  if (node.items) {
    const detail = constraints(node.items, schema);
    parts.push(`Items: ${types(node.items, schema).join(' or ') || 'any'}${detail ? ` (${detail})` : ''}`);
  }
  const text = parts.join('; ');
  return text ? text[0].toUpperCase() + text.slice(1) : '';
}

function conditionText(condition, schema) {
  const parts = (condition.required ?? []).map((key) => `${code(key)} is present`);
  for (const [key, node] of Object.entries(condition.properties ?? {})) {
    const detail = constraints(node, schema);
    parts.push(`${code(key)}: ${detail || `Type: ${types(node, schema).join(' or ')}`}`);
  }
  return parts.join('; ');
}

export function schemaDocs(schema) {
  const provider = schema.$defs.provider;
  const sections = [
    '# Provider schema reference',
    '',
    'Generated from [`data/schema.json`](../data/schema.json) by `node scripts/schema-docs.mjs` (also run by `npm run build`). Do not edit this file by hand.',
    '',
    'Fields follow schema order. Required means the key must be present; nullable means its base schema allows `null`. Optional and nullable are independent. Conditional rules can narrow the types and nullability listed in the field tables. Nested fields are required only when their containing object is present and non-null.',
    '',
    'Descriptions are copied from each property itself. “No description in schema.” marks a missing property description, even when a shared definition has one. This reference describes the JSON Schema; additional integrity rules live in [`scripts/validate.mjs`](../scripts/validate.mjs).',
    '',
  ];

  function table(object, prefix = '') {
    const conditional = new Set((object.allOf ?? []).flatMap((rule) => [
      ...(rule.then?.required ?? []), ...(rule.else?.required ?? []),
    ]));
    sections.push(`## ${prefix ? code(prefix.slice(0, -1)) : 'Provider fields'}`, '',
      '| Field | Type (excluding null) | Nullable | Required | Allowed values / constraints | Description |',
      '| --- | --- | --- | --- | --- | --- |');
    for (const [name, property] of Object.entries(object.properties)) {
      const values = types(property, schema);
      const type = values.filter((value) => value !== 'null').join(' or ') || (values.includes('null') ? 'null only' : 'any');
      const required = object.required?.includes(name) ? 'Yes' : conditional.has(name) ? 'Conditional' : 'No';
      sections.push(`| \`${cell(prefix + name)}\` | ${cell(type)} | ${values.includes('null') ? 'Yes' : 'No'} | ${required} | ${constraints(property, schema) || '—'} | ${cell(property.description ?? 'No description in schema.')} |`);
    }
    sections.push('');
    for (const [name, property] of Object.entries(object.properties)) {
      const nested = dereference(property, schema);
      if (nested.properties) table(nested, `${prefix}${name}.`);
    }
  }
  table(provider);

  if (provider.allOf?.length) {
    sections.push('## Conditional rules', '',
      'These schema branches apply in addition to the base field definitions. A required key can still be nullable unless its branch narrows the type.', '',
      '| When | Branch | Required keys | Additional constraints |',
      '| --- | --- | --- | --- |');
    for (const rule of provider.allOf) {
      for (const branch of ['then', 'else']) {
        if (!rule[branch]) continue;
        const value = rule[branch];
        const detail = Object.entries(value.properties ?? {}).map(([key, node]) => {
          const kind = types(node, schema);
          const limits = constraints(node, schema);
          return `${code(key)} — ${[kind.length ? `Type: ${cell(kind.join(' or '))}` : '', limits].filter(Boolean).join('; ')}`;
        }).join('<br>');
        sections.push(`| ${conditionText(rule.if, schema)} | ${branch === 'then' ? 'Condition matches' : 'Otherwise'} | ${(value.required ?? []).map(code).join(', ') || '—'} | ${detail || '—'} |`);
      }
    }
    sections.push('');
  }
  return sections.join('\n');
}

export function writeSchemaDocs(schemaPath = DEFAULT_SCHEMA, outputPath = DEFAULT_OUTPUT) {
  writeFileSync(outputPath, schemaDocs(JSON.parse(readFileSync(schemaPath, 'utf8'))));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeSchemaDocs(process.argv[2], process.argv[3]);
}
